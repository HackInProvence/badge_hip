"""
Single source of truth for the CTF flags of the badge AND the CTFd import.

SPOILERS: this file holds the plaintext flags of the organizers.

- BADGE_FLAGS: flags revealed by the badge itself (src/menu/ctf.c registry), when a condition on the saved state
  is met (a game won, a record beaten, a multiplayer victory). Flag 0 (Konami) is set by the code page.
- EXTERNAL_FLAGS: flags revealed by other modules (crypto challenges, "Cigale bavarde"); listed here only so the
  CTFd gets every flag. Their plaintext MUST match the module (crypto_ctf_make.py, babble.c).

The firmware only stores each flag XORed with "cigale" and 7*i (nothing readable with "strings").

Usage:
    python tools/ctf_flags.py --update   # rewrite the GENERATED block of src/menu/ctf.c
    python tools/ctf_flags.py --ctfd     # print the CTFd challenges as JSON (used by ctfd/import_challenges.py)
    python tools/ctf_flags.py --answers  # print every challenge with its flag (for the organizers)
"""

