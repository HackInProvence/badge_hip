def full(flag):
    return PREFIX + flag + '}'


def obf(flag):
    b = full(flag).encode()
    return [b[i] ^ KEY[i % 6] ^ ((i * 7) & 0xFF) for i in range(len(b))]


def c_cond(cond):
    if cond == 'code':
        return None
    kind, arg = cond.split(':', 1)
    if kind == 'game':
        return f's->game_records[{arg}] != GAMES_NO_RECORD'
    if kind == 'puzzle':
        return f's->puzzle_records[{arg}] && s->puzzle_records[{arg}] != 0xFFFF'
    if kind == 'achv':
        return f'achv_unlocked({arg})'
    raise SystemExit(f'unknown cond {cond}')


def gen_c():
    out = ['/* GENERATED by tools/ctf_flags.py --update: do not edit by hand. */']
    out.append('enum {')
    for f in BADGE_FLAGS:
        out.append(f'    FLAG_{f["id"]},')
    out.append('    CTF_FLAG_COUNT,')
    out.append('};')
    out.append('')
    out.append('static const char *const CTF_FLAG_NAMES[CTF_FLAG_COUNT] = {')
    for f in BADGE_FLAGS:
        out.append(f'    [FLAG_{f["id"]}] = N_("{f["name"]}"),')
    out.append('};')
    out.append('')
    for f in BADGE_FLAGS:
        by = obf(f['flag'])
        arr = ', '.join('0x%02X' % b for b in by)
        out.append(f'static const uint8_t CTF_BYTES_{f["id"]}[] = {{{arr}}};')
    out.append('')
    out.append('static const struct { const uint8_t *b; uint8_t len; } CTF_FLAG_TABLE[CTF_FLAG_COUNT] = {')
    for f in BADGE_FLAGS:
        out.append(f'    [FLAG_{f["id"]}] = {{CTF_BYTES_{f["id"]}, sizeof(CTF_BYTES_{f["id"]})}},')
    out.append('};')
    out.append('')
    out.append('/* Reveal condition from the saved state (FLAG_KONAMI is set by the code page). */')
    out.append('static bool ctf_flag_condition(int id, const store_t *s) {')
    out.append('    (void)s;')
    out.append('    switch (id) {')
    for f in BADGE_FLAGS:
        c = c_cond(f['cond'])
        if c:
            out.append(f'    case FLAG_{f["id"]}: return {c};')
    out.append('    default: return false;')
    out.append('    }')
    out.append('}')
    out.append('/* END GENERATED */')
    return '\n'.join(out)


def update_c():
    text = open(C_FILE, encoding='utf-8').read()
    block = gen_c()
    pat = re.compile(r'/\* GENERATED by tools/ctf_flags\.py.*?/\* END GENERATED \*/', re.S)
    if not pat.search(text):
        raise SystemExit('markers not found in ctf.c (add the GENERATED block once)')
    text = pat.sub(lambda _: block, text)
    open(C_FILE, 'w', encoding='utf-8').write(text)
    print(f'updated {C_FILE}: {len(BADGE_FLAGS)} badge flags')


def ctfd_challenges():
    chals = []
    for f in BADGE_FLAGS + EXTERNAL_FLAGS:
        chals.append(dict(name=f['name'], category=f['cat'], value=100, type='standard',
                          flag=full(f['flag']),
                          description=f'Débloqué sur le badge SecSea ({f["cat"]}). Recopie le flag affiché.'))
    return chals


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--update', action='store_true')
    ap.add_argument('--ctfd', action='store_true')
    ap.add_argument('--answers', action='store_true')
    a = ap.parse_args()
    if a.update:
        update_c()
    elif a.ctfd:
        print(json.dumps(ctfd_challenges(), ensure_ascii=False, indent=2))
    elif a.answers:
        for f in BADGE_FLAGS + EXTERNAL_FLAGS:
            print(f'{f["name"]:18s} {full(f["flag"])}')
    else:
        print(gen_c())


if __name__ == '__main__':
    main()
