def check():
    for name, rows in ICONS:
        assert len(rows) == 16, name
        for r in rows:
            assert len(r) == 16, (name, r)


def header():
    out = ['/* Generated by tools/skills_icons.py: edit the drawings there */', '',
           '#ifndef _SKILLS_ICONS_H', '#define _SKILLS_ICONS_H', '', '#include <stdint.h>', '',
           f'#define SKILLS_ICONS {len(ICONS)}', '',
           '/* 16x16, one row per uint16_t, the leftmost pixel in the high bit, 1 = black */',
           'static const uint16_t SKILLS_ICON_BITS[SKILLS_ICONS][16] = {']
    for name, rows in ICONS:
        vals = [int(r.replace('#', '1').replace('.', '0'), 2) for r in rows]
        out.append(f'    {{{", ".join(f"0x{v:04X}" for v in vals)}}},  /* {name} */')
    out += ['};', '', '#endif /* _SKILLS_ICONS_H */', '']
    return '\n'.join(out)


def preview(path):
    from PIL import Image, ImageDraw
    z, cols = 4, 5
    cell = 16 * z + 20
    rows_n = (len(ICONS) + cols - 1) // cols
    img = Image.new('L', (cols * cell, rows_n * (cell + 14)), 255)
    d = ImageDraw.Draw(img)
    for i, (name, rows) in enumerate(ICONS):
        x0, y0 = (i % cols) * cell + 10, (i // cols) * (cell + 14) + 6
        for y, r in enumerate(rows):
            for x, c in enumerate(r):
                if c == '#':
                    d.rectangle([x0 + x * z, y0 + y * z, x0 + x * z + z - 1, y0 + y * z + z - 1], fill=0)
        d.text((x0, y0 + 16 * z + 2), name.encode('ascii', 'replace').decode(), fill=0)
    img.save(path)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[1])
    parser.add_argument('--preview')
    args = parser.parse_args()
    check()
    here = os.path.dirname(os.path.abspath(__file__))
    with open(os.path.join(here, '..', 'src', 'menu', 'skills_icons.h'), 'w', encoding='utf-8', newline='\n') as f:
        f.write(header())
    if args.preview:
        preview(args.preview)
