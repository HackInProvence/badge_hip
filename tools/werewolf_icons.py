def pixels(key):
    """The rows of an icon (lists of 0 / 1, 1 = black), checked."""
    rows = [r.strip() for r in ICONS[key].strip('\n').split('\n')]
    if len(rows) != SIZE or any(len(r) != SIZE or set(r) - set('#.') for r in rows):
        sys.exit(f'icon {key}: {SIZE} rows of {SIZE} characters "#" or "." expected')
    return [[1 if c == '#' else 0 for c in r] for r in rows]


def c_block():
    out = [BEGIN]
    for key in ICONS:
        data = []
        for row in pixels(key):
            for x in range(0, SIZE, 8):
                data.append(sum(row[x + i] << (7 - i) for i in range(8)))
        out.append(f'static const uint8_t ICON_{key}[WW_ICON_BYTES] = {{')
        for i in range(0, len(data), 16):
            out.append('    ' + ', '.join(f'0x{b:02X}' for b in data[i:i + 16]) + ',')
        out.append('};')
    out.append(END)
    return '\n'.join(out)


def updated_source():
    src = open(C_FILE, encoding='utf-8').read()
    a, b = src.find(BEGIN), src.find(END)
    if a < 0 or b < 0:
        sys.exit(f'markers not found in {C_FILE}')
    return src, src[:a] + c_block() + src[b + len(END):]


def save_png(path, rows):
    """Black and white PNG (no dependency): rows of 0 (black) / 1 (white)."""
    h, w = len(rows), len(rows[0])
    raw = b''.join(b'\x00' + bytes(255 if v else 0 for v in r) for r in rows)

    def chunk(kind, data):
        c = struct.pack('>I', len(data)) + kind + data
        return c + struct.pack('>I', zlib.crc32(kind + data) & 0xFFFFFFFF)
    with open(path, 'wb') as f:
        f.write(b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', w, h, 8, 0, 0, 0, 0)) +
                chunk(b'IDAT', zlib.compress(raw)) + chunk(b'IEND', b''))


def contact_sheet(path, zoom=6, cols=5):
    keys = list(ICONS)
    cell = SIZE + 4
    n_rows = (len(keys) + cols - 1) // cols
    img = [[1] * (cols * cell * zoom) for _ in range(n_rows * cell * zoom)]
    for i, key in enumerate(keys):
        ox, oy = (i % cols) * cell * zoom, (i // cols) * cell * zoom
        for y, row in enumerate(pixels(key)):
            for x, v in enumerate(row):
                if v:
                    for dy in range(zoom):
                        for dx in range(zoom):
                            img[oy + y * zoom + dy][ox + x * zoom + dx] = 0
    save_png(path, img)
    print(f'{len(keys)} icons in {path}, in this order: ' + ', '.join(keys))


def main():
    parser = argparse.ArgumentParser(description='Illustrations of the cards of the loup-garou')
    parser.add_argument('--png', help='contact sheet of the icons instead (PNG file)')
    parser.add_argument('--check', action='store_true', help='only check that werewolf_cards.c is up to date')
    args = parser.parse_args()
    if args.png:
        contact_sheet(args.png)
        return
    src, new = updated_source()
    if args.check:
        if src != new:
            sys.exit(f'{C_FILE} is not up to date: run python tools/werewolf_icons.py')
        print('icons up to date')
        return
    if src != new:
        with open(C_FILE, 'w', encoding='utf-8', newline='\n') as f:
            f.write(new)
    print(f'{len(ICONS)} icons written in {C_FILE}')


if __name__ == '__main__':
    main()
