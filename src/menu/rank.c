#define ZOOM 2

void rank_draw_portrait(uint8_t *fb, int x, int y, uint8_t level, int zoom) {
    const uint8_t *bits = RANK_PORTRAITS[level < 1 ? 0 : level > ACHV_LEVELS ? ACHV_LEVELS - 1 : level - 1];
    for (int r = 0; r < RANK_PORTRAIT_SIZE; ++r)
        for (int c = 0; c < RANK_PORTRAIT_SIZE; ++c)
            if (bits[r * (RANK_PORTRAIT_SIZE / 8) + c / 8] & (0x80 >> (c % 8)))
                gfx_fill_rect(fb, x + c * zoom, y + r * zoom, zoom, zoom, GFX_BLACK);
}

static void rank_render(uint8_t *fb) {
    char text[48];
    uint8_t level = achv_level();
    snprintf(text, sizeof(text), _("Grade %u / %u   %lu XP"), level, ACHV_LEVELS, (unsigned long)achv_xp());
    gfx_text(fb, GFX_WIDTH/2, 2, &gfx_font_small, text, GFX_BLACK, GFX_ALIGN_CENTER);
    const int size = RANK_PORTRAIT_SIZE * ZOOM;
    rank_draw_portrait(fb, (GFX_WIDTH - size) / 2, 22, level, ZOOM);
    /* The name of the rank in a black band, and what the next one needs */
    const int band_y = 22 + size + 4;
    gfx_fill_rect(fb, 0, band_y, GFX_WIDTH, GFX_HEIGHT - band_y, GFX_BLACK);
    const char *name = achv_level_name(level);
    const gfx_font_t *font = gfx_text_width(&gfx_font_medium, name) <= GFX_WIDTH - 6 ? &gfx_font_medium
                                                                                      : &gfx_font_small;
    gfx_text(fb, GFX_WIDTH/2, band_y + 2, font, name, GFX_WHITE, GFX_ALIGN_CENTER);
    if (level < ACHV_LEVELS)
        snprintf(text, sizeof(text), _("Grade suivant : %lu XP"), (unsigned long)achv_level_xp(level + 1));
    else
        snprintf(text, sizeof(text), "%s", _("Grade le plus haut !"));
    gfx_text(fb, GFX_WIDTH/2, band_y + 23, &gfx_font_small, text, GFX_WHITE, GFX_ALIGN_CENTER);
}

static void rank_start(absolute_time_t now) {
    (void)now;
    printf("rank: level %u, %s, %lu XP\n", achv_level(), achv_level_name(achv_level()), (unsigned long)achv_xp());
    /* Shown like the screensaver: full waveform of the screen (no ghost), stays without power, any button leaves */
    app_show_still(rank_render);
}

static bool rank_buttons(const app_buttons_t *b, absolute_time_t now) {
    (void)now;
    return ! b->pressed;
}

static void rank_page(uint8_t *fb, absolute_time_t now) {
    (void)now;
    rank_render(fb);
}

const app_t app_rank = {
    .name = N_("Mon grade"),
    .start = rank_start,
    .buttons = rank_buttons,
    .render = rank_page,
    .no_saver = true,  /* It is made to stay */
};
