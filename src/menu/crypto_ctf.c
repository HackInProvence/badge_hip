#define COUNT ((int)(sizeof(CHALLENGES) / sizeof(CHALLENGES[0])))
#define ALL_SOLVED (COUNT >= 32 ? 0xFFFFFFFFu : (1u << (COUNT & 31)) - 1)


static const challenge_t *get(int i) {
    return i >= 0 && i < COUNT ? &CHALLENGES[i] : NULL;
}

/* The 8 bytes XORed with the piece of the flag of the challenge i */
static uint64_t piece_stream(int i) {
    uint8_t data[6] = {'p', 'i', 'e', 'c', 'e', (uint8_t)i};
    return score_code_siphash(KEY, data, sizeof(data));
}

/* Uppercase, without the spaces at the ends nor the repeated spaces: the length, -1 if too long or not A-Z 0-9 */
static int normalize(const char *in, char *out) {
    int n = 0;
    bool space = false;
    for (; *in; ++in) {
        char c = *in;
        if (c == ' ' || c == '\t') {
            space = n > 0;  /* Not at the start */
            continue;
        }
        if (c >= 'a' && c <= 'z')
            c -= 'a' - 'A';
        if (! ((c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9')))
            return -1;
        if (n + space + 1 > CRYPTO_CTF_ANSWER_MAX)
            return -1;
        if (space)
            out[n++] = ' ';
        out[n++] = c;
        space = false;
    }
    return n;
}


int crypto_ctf_count(void) {
    return COUNT;
}


const char *crypto_ctf_title(int i) {
    const challenge_t *c = get(i);
    return c ? c->title : "";
}


const char *crypto_ctf_text(int i) {
    const challenge_t *c = get(i);
    return c ? c->text : "";
}


const char *crypto_ctf_hint(int i) {
    const challenge_t *c = get(i);
    return c ? c->hint : "";
}


const char *crypto_ctf_morse(int i) {
    const challenge_t *c = get(i);
    return c ? c->morse : NULL;
}


bool crypto_ctf_check(int i, const char *answer) {
    const challenge_t *c = get(i);
    if (! c || ! answer)
        return false;
    uint8_t data[2 + CRYPTO_CTF_ANSWER_MAX];
    data[0] = (uint8_t)i;
    data[1] = ':';
    int n = normalize(answer, (char *)data + 2);
    if (n <= 0)
        return false;
    return score_code_siphash(KEY, data, 2 + n) == c->hash;
}


bool crypto_ctf_piece(int i, uint32_t solved_mask, char *buf, int len) {
    const challenge_t *c = get(i);
    if (! c || ! (solved_mask & (1u << i)) || len <= c->piece_len)
        return false;
    uint64_t s = piece_stream(i);
    for (int k = 0; k < c->piece_len; ++k)
        buf[k] = c->piece[k] ^ (uint8_t)(s >> (8 * k));
    buf[c->piece_len] = 0;
    return true;
}


bool crypto_ctf_final_flag(uint32_t solved_mask, char *buf, int len) {
    static const char START[] = "SECSEA{";
    if (len > 0)
        buf[0] = 0;
    int total = sizeof(START) - 1 + 1;  /* With the '}' */
    for (int i = 0; i < COUNT; ++i)
        total += CHALLENGES[i].piece_len;
    if ((solved_mask & ALL_SOLVED) != ALL_SOLVED || len <= total)
        return false;
    int pos = sizeof(START) - 1;
    memcpy(buf, START, pos);
    for (int i = 0; i < COUNT; ++i) {
        crypto_ctf_piece(i, solved_mask, buf + pos, len - pos);
        pos += CHALLENGES[i].piece_len;
    }
    buf[pos++] = '}';
    buf[pos] = 0;
    return true;
}
