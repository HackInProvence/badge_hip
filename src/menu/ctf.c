/* Reveal condition from the saved state (FLAG_KONAMI is set by the code page). */
static bool ctf_flag_condition(int id, const store_t *s) {
    (void)s;
    switch (id) {
    case FLAG_MORPION: return s->game_records[GAME_TICTACTOE] != GAMES_NO_RECORD;
    case FLAG_PUISSANCE4: return s->game_records[GAME_CONNECT4] != GAMES_NO_RECORD;
    case FLAG_SIMON: return s->game_records[GAME_SIMON] != GAMES_NO_RECORD;
    case FLAG_REFLEXES: return s->game_records[GAME_REFLEX] != GAMES_NO_RECORD;
    case FLAG_SNAKE: return s->game_records[GAME_SNAKE] != GAMES_NO_RECORD;
    case FLAG_DEMINEUR: return s->puzzle_records[PUZZLE_MINES] && s->puzzle_records[PUZZLE_MINES] != 0xFFFF;
    case FLAG_J2048: return s->puzzle_records[PUZZLE_2048] && s->puzzle_records[PUZZLE_2048] != 0xFFFF;
    case FLAG_TAQUIN: return s->puzzle_records[PUZZLE_TAQUIN] && s->puzzle_records[PUZZLE_TAQUIN] != 0xFFFF;
    case FLAG_SOKOBAN: return s->puzzle_records[PUZZLE_SOKOBAN] && s->puzzle_records[PUZZLE_SOKOBAN] != 0xFFFF;
    case FLAG_MASTERMIND: return s->puzzle_records[PUZZLE_MASTERMIND] && s->puzzle_records[PUZZLE_MASTERMIND] != 0xFFFF;
    case FLAG_PENDU: return s->puzzle_records[PUZZLE_PENDU] && s->puzzle_records[PUZZLE_PENDU] != 0xFFFF;
    case FLAG_DUEL: return achv_unlocked(ACHV_DUEL_WIN);
    case FLAG_BATAILLE: return achv_unlocked(ACHV_BATTLE_WIN);
    case FLAG_LOUP_GAROU: return achv_unlocked(ACHV_WEREWOLF_WIN);
    case FLAG_ASSASSIN: return achv_unlocked(ACHV_ASSASSIN_WIN);
    case FLAG_TIR_CORDE: return achv_unlocked(ACHV_TUG_WIN);
    default: return false;
    }
}
/* END GENERATED */

static const char key[] = "cigale";

static void set_found(int id) {
    store_t *s = store_get();
    if (!(s->flags_found & (1u << id))) {
        s->flags_found |= 1u << id;
        store_changed();
    }
}


void ctf_code_start(void) {
    n_typed = 0;
}

int ctf_code_press(uint8_t btn_mask) {
    if (n_typed < CTF_CODE_LEN && btn_mask)
        typed[n_typed++] = btn_mask;
    return n_typed;
}

void ctf_code_text(char *buf, int len) {
    /* ^ v for the flanks, < > for the wings: the player sees what he typed, not whether it is right */
    int pos = 0;
    buf[0] = 0;
    for (int i = 0; i < n_typed && pos < len - 3; ++i) {
        char c = typed[i] == BTN_Y ? '^' : typed[i] == BTN_X ? 'v' : typed[i] == BTN_A ? '<' : '>';
        pos += snprintf(buf + pos, len - pos, "%c ", c);
    }
}

bool ctf_code_check(void) {
    if (n_typed != CTF_CODE_LEN || memcmp(typed, KONAMI, CTF_CODE_LEN))
        return false;
    set_found(FLAG_KONAMI);
    achv_unlock(ACHV_CTF_FLAG);
    return true;
}


int ctf_count(void) {
    return CTF_FLAG_COUNT;
}

const char *ctf_flag_name(int i) {
    return (i >= 0 && i < CTF_FLAG_COUNT) ? CTF_FLAG_NAMES[i] : "";
}

bool ctf_flag_is_found(int i) {
    return i >= 0 && i < CTF_FLAG_COUNT && (store_get()->flags_found >> i & 1);
}

const char *ctf_flag(int i, char *buf, int len) {
    if (i < 0 || i >= CTF_FLAG_COUNT || !ctf_flag_is_found(i))
        return NULL;
    const uint8_t *b = CTF_FLAG_TABLE[i].b;
    int n = CTF_FLAG_TABLE[i].len;
    if (!b || len <= n)
        return NULL;
    for (int k = 0; k < n; ++k)
        buf[k] = b[k] ^ key[k % 6] ^ (uint8_t)(k * 7);
    buf[n] = 0;
    return buf;
}

int ctf_found_count(void) {
    int n = 0;
    for (int i = 0; i < CTF_FLAG_COUNT; ++i)
        n += (store_get()->flags_found >> i) & 1;
    return n;
}

bool ctf_refresh(char *name, int len) {
    const store_t *s = store_get();
    for (int i = 0; i < CTF_FLAG_COUNT; ++i) {
        if (!(s->flags_found & (1u << i)) && ctf_flag_condition(i, s)) {
            set_found(i);
            achv_unlock(ACHV_CTF_FLAG);
            if (name && len > 0)
                snprintf(name, len, "%s", tr(CTF_FLAG_NAMES[i]));
            return true;  /* one per call: the main loop shows a notification, then calls again */
        }
    }
    return false;
}
